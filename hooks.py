# 钩子系统：把对话流程的不同阶段抽象成一个个独立节点。
# 之所以这样做，是想让 chat.py 的循环只关心"流程先后"，不关心"每步具体做什么"，
# 各节点内部实现可以各自独立演进而互不影响，也方便以后插入新的处理节点。

import llm
import make_massage
import tool
# ---------------- 对话生命周期节点 ----------------

def 会话开始():
    # 每轮对话的第一步：写入初始系统提示（助手身份 + 技能说明），初始化消息历史
    make_massage.预设初始消息()
    print("会话开始")



def 用户输入():
    # 读取用户本轮输入，并追加为 user 消息到 box["消息"]；"退出/111"会置结束标志
    make_massage.用户输入()
    print("用户输入")



def 模型调用前():
    # 发送给模型前：把上轮的 assistant 回复和工具结果拼进消息历史，再挂载可用工具定义
    llm.输入消息拼接()
    print("模型调用前")

def use_model():
    # 真正调用 LLM：按 box["主模型"] 选模型，把回复写回 box["回复消息"]
    llm.use_llm()

def 模型调用后():
    # 模型回复后：剪出 content 与 tool_calls 存进最终回复，并判断本轮是否需要调用工具
    llm.返回消息处理()
    tool.工具判断()
    print("模型调用后")

def 工具调用前():
    # 触发工具调用前：把模型返回的工具调用指令（tool_calls）存进 box["调用工具"]
    llm.工具调用写入()
    print("工具调用前")

def use_tool():   
    # 真正执行工具：遍历工具调用指令，按映射表执行本地函数，并把结果回填
    tool.工具调用执行()
    print()

def 工具调用后():
    print("工具调用后")

def 工具循环结束():
    # 模型不再请求工具、给出最终答案时，结束本轮内层工具调用循环
    print("工具循环结束")


def 对话结束():
    # 用户要求退出时收尾，结束整轮对话
    print("对话结束")










