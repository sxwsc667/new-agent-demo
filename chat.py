# 多轮对话循环框架（三种模式）：
# 用 hooks 里的节点函数把流程"先后顺序"写在这里，每步具体执行逻辑由 hooks 转发给对应模块，
# 因而本文件只负责循环跳转与退出判断，不参与具体业务实现。

import hooks
from box import box



# ============ 模式二：ReAct（对话大循环 + 工具调用内循环） ============
def ReAct():
    """
    流程：对话开始 → [循环起点 → [模型调用前 → 模型调用后 → (工具调用前 → 工具调用后)*]* → 循环结束]* → 对话结束
    
    外层：用户输入循环（一次输入一轮）
    内层：单个问题的多轮工具调用循环（模型可能连续请求多次工具，直到给出最终答案）
    """
    hooks.会话开始()
    
    # 外层循环：用户每次输入
    while True:
        hooks.用户输入()
        # 用户输入"退出/111"时 用户输入() 会置 box["结束会话"]，据此结束整个对话
        if box["结束会话"]:
            hooks.对话结束()
            break  # 临时，实际由退出条件控制   

        else:
            # 内层循环：ReAct 多轮推理
            while True:
                hooks.模型调用前()
                hooks.use_model()
                hooks.模型调用后()
                
                # 模型返回时 tool_calls 有值表示还想调用工具，则继续内循环；
                # 判断收敛在 工具判断() 写入的 box["是否调用工具"] 开关上
                if box["是否调用工具"]:
                    hooks.工具调用前()
                    hooks.use_tool()
                    hooks.工具调用后()
                    # 继续内循环（下一次 模型调用前 会把工具结果回填给模型）
                else:
                    # 模型给出最终答案、不再要工具，跳出内循环去等下一条用户输入
                    hooks.工具循环结束()
                    break
            



